class CloudSQLTests(unittest.TestCase):
    def test_question_mark_literal_is_not_a_placeholder(self):
        self.assertEqual(placeholders("SELECT '?' AS text WHERE value=?"),"SELECT '?' AS text WHERE value=%s")
    def test_percent_in_parameterized_literal_is_escaped(self):
        self.assertEqual(placeholders("SELECT '50%' WHERE key=?"),"SELECT '50%%' WHERE key=%s")
    def test_binary_null_and_text_have_distinct_digests(self):
        self.assertNotEqual(row_digest([(b'x',None)]),row_digest([('x','')]))
    def test_identity_and_unique_are_preserved(self):
        info=schema_info('CREATE TABLE manual_actions(id INTEGER PRIMARY KEY,account TEXT NOT NULL,peer TEXT NOT NULL,confirmed INTEGER NOT NULL,status TEXT NOT NULL,UNIQUE(account,peer))')
        ddl=create_sql(info)
        self.assertIn('GENERATED BY DEFAULT AS IDENTITY',ddl)
        self.assertIn('UNIQUE ("account","peer")',ddl)
        self.assertIn('CHECK (confirmed=1)',ddl)
    def test_ignore_does_not_turn_into_replace(self):
        sql,_=translate('INSERT OR IGNORE INTO chain_actions(chat) VALUES(?)',{})
        self.assertEqual(sql,'INSERT INTO chain_actions(chat) VALUES(%s) ON CONFLICT DO NOTHING')
    def test_replace_requires_known_pk(self):
        with self.assertRaises(ValueError):translate('INSERT OR REPLACE INTO unknown VALUES(?)',{})
    def test_id_returning_and_replace(self):
        info=schema_info('CREATE TABLE ids(id INTEGER PRIMARY KEY,value TEXT)')
        sql,key=translate('INSERT OR IGNORE INTO ids(value) VALUES(?)',{'ids':info})
        self.assertEqual(key,'id');self.assertTrue(sql.endswith('DO NOTHING RETURNING "id"'))
    def test_unknown_rowid_is_fail_closed(self):
        with self.assertRaises(ValueError):translate('SELECT * FROM chain_actions ORDER BY rowid',{})
    def test_multiple_source_statements_rejected(self):
        with self.assertRaises(sqlite3.ProgrammingError):schema_info('CREATE TABLE x(id INTEGER PRIMARY KEY); DROP TABLE x')
    def test_schema_identifier_rejected(self):
        with self.assertRaises(ValueError):schema_info('CREATE TABLE "bad-name"(id TEXT PRIMARY KEY)')
    def test_canonical_path_only(self):
        with tempfile.TemporaryDirectory() as folder,patch.dict(os.environ,LOCALAPPDATA=folder,DVK_MORELOGIN='0'):
            p=Path(folder)/'DvkAssistant';p.mkdir();(p/'database.dpapi').write_bytes(b'corrupt')
            self.assertTrue(cloud.enabled(p/'assistant.sqlite3'))
            self.assertFalse(cloud.enabled(Path(folder)/'test.sqlite3'))
            with patch.dict(os.environ,DVK_MORELOGIN='1'):self.assertFalse(cloud.enabled(p/'assistant.sqlite3'))
    def test_corrupt_config_does_not_fall_back_to_local(self):
        with tempfile.TemporaryDirectory() as folder,patch.dict(os.environ,LOCALAPPDATA=folder,DVK_MORELOGIN='0'):
            p=Path(folder)/'DvkAssistant';p.mkdir();(p/'database.dpapi').write_bytes(b'bad')
            with patch('cloud_database.load',side_effect=cloud.CloudDatabaseError('cloud-database-config-invalid')),patch('cloud_database.sqlite3.connect') as local:
                with self.assertRaises(cloud.CloudDatabaseError):cloud.connect(p/'assistant.sqlite3')
                local.assert_not_called()
    def test_missing_credentials_with_cloud_marker_cannot_use_old_sqlite(self):
        with tempfile.TemporaryDirectory() as folder,patch.dict(os.environ,LOCALAPPDATA=folder,DVK_MORELOGIN='0'):
            p=Path(folder)/'DvkAssistant';p.mkdir();(p/'database-cloud-primary.json').write_text('{}')
            self.assertTrue(cloud.enabled(p/'assistant.sqlite3'))
            with patch('cloud_database.sqlite3.connect') as local:
                with self.assertRaises(cloud.CloudDatabaseError):cloud.connect(p/'assistant.sqlite3')
                local.assert_not_called()
    def test_local_mode_remains_sqlite(self):
        with tempfile.TemporaryDirectory() as folder,patch.dict(os.environ,LOCALAPPDATA=folder):
            p=Path(folder)/'test.sqlite3';db=cloud.connect(p);self.assertIsInstance(db,sqlite3.Connection);db.close()
    def test_migration_does_not_infer_sent_status(self):
        from inspect import getsource
        from cloud_migration import import_source
        src=getsource(import_source)
        self.assertNotIn('UPDATE chain_actions',src)
        self.assertIn('cloud-dataset-already-live',src)
        self.assertIn('source_hash!=dest_hash',src)
        self.assertIn('require_latest_journals',src)

