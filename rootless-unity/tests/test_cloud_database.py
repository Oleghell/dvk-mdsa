class FakeCursor:
    description=None;rowcount=0
class FakeRaw:
    closed=False
    def __init__(self):self.queries=[]
    def execute(self,sql,params=None,**kwargs):self.queries.append((sql,params));return FakeCursor()
    def close(self):self.closed=True

class CloudTransactions(unittest.TestCase):
    def test_write_lock_precedes_mutation_and_no_retry(self):
        raw=FakeRaw();db=cloud.Connection(raw,{},{});db.execute('BEGIN IMMEDIATE')
        db.execute('UPDATE x SET y=?',(1,));db.execute('COMMIT')
        sql=[q for q,_ in raw.queries]
        advisory=next(i for i,q in enumerate(sql) if 'pg_advisory_xact_lock' in q)
        mutation=next(i for i,q in enumerate(sql) if q.startswith('UPDATE'))
        self.assertLess(advisory,mutation)
        self.assertEqual(sum('UPDATE' in q for q in sql),1)
    def test_readonly_has_no_write_lock(self):
        raw=FakeRaw();db=cloud.Connection(raw,{},{});db.execute('PRAGMA query_only=ON');db.execute('BEGIN')
        self.assertIn('READ ONLY',raw.queries[0][0]);self.assertFalse(any('advisory' in q for q,_ in raw.queries))
        with self.assertRaises(cloud.CloudDatabaseError):db.execute('DELETE FROM x')
    def test_rollback_discards_schema_cache(self):
        raw=FakeRaw();db=cloud.Connection(raw,{},{});db.execute('BEGIN IMMEDIATE')
        db.execute('CREATE TABLE IF NOT EXISTS x(id TEXT PRIMARY KEY)');self.assertIn('x',db.pending)
        db.execute('ROLLBACK');self.assertNotIn('x',db.schemas);self.assertFalse(db.pending)

class CloudCutoverOrdering(unittest.TestCase):
    def fixture(self,folder):
        from unittest.mock import MagicMock
        cfg=CloudDriverSettings().config()
        root=Path(folder)/'DvkAssistant';root.mkdir()
        path=root/'assistant.sqlite3'
        db=sqlite3.connect(path);db.execute('CREATE TABLE retained(id INTEGER PRIMARY KEY)');db.commit();db.close()
        config=Path(folder)/'connection.json';config.write_text(json.dumps(cfg))
        raw=MagicMock();raw.__enter__.return_value=raw
        raw.execute.return_value.fetchone.return_value=(cloud.PROTOCOL,cfg['dataset'],False)
        return cfg,root,path,config,raw
    def test_cloud_selection_is_durable_before_activation_and_failure_stays_closed(self):
        import cloud_setup
        with tempfile.TemporaryDirectory() as folder,patch.dict(os.environ,LOCALAPPDATA=folder,DVK_MORELOGIN='0'):
            cfg,root,path,config,raw=self.fixture(folder)
            original=path.read_bytes()
            def migration(*args,**kwargs):
                self.assertTrue((root/'database.dpapi').exists())
                self.assertTrue((root/'database-cloud-primary.json').exists())
                self.assertTrue(kwargs['activate'])
                raise cloud.CloudDatabaseError('migration-verification-failed')
            with patch('cloud_setup.raw_connect',return_value=raw),patch('cloud_setup.import_source',side_effect=migration),patch('telegram_notify.protect',return_value=b'protected'):
                with self.assertRaisesRegex(cloud.CloudDatabaseError,'migration-verification-failed'):cloud_setup.install(config)
            self.assertEqual(path.read_bytes(),original)
            self.assertTrue(cloud.enabled(path));self.assertEqual(len(list(root.glob('assistant-pre-supabase-*.sqlite3'))),1)
            with patch('cloud_database.load',side_effect=cloud.CloudDatabaseError()),patch('cloud_database.sqlite3.connect') as fallback:
                with self.assertRaises(cloud.CloudDatabaseError):cloud.connect(path)
                fallback.assert_not_called()
    def test_failed_dpapi_save_never_activates_remote_database(self):
        import cloud_setup
        with tempfile.TemporaryDirectory() as folder,patch.dict(os.environ,LOCALAPPDATA=folder,DVK_MORELOGIN='0'):
            cfg,root,path,config,raw=self.fixture(folder)
            with patch('cloud_setup.raw_connect',return_value=raw),patch('cloud_setup.import_source') as migrate,patch('telegram_notify.protect',side_effect=[b'check-ok',OSError('disk or DPAPI failure')]):
                with self.assertRaises(OSError):cloud_setup.install(config)
                migrate.assert_not_called()
            self.assertFalse((root/'database.dpapi').exists())

class CloudStartupFailures(unittest.TestCase):
    def test_lock_timeout_is_fixed_code_without_exception_body(self):
        class LockError(Exception):sqlstate='55P03'
        raw=FakeRaw()
        def failed(*a,**kw):raise LockError('PRIVATE SQL, contact and password')
        raw.execute=failed
        with self.assertRaises(cloud.CloudDatabaseError) as result:
            cloud.Connection(raw,{},{})._run('SELECT pg_advisory_xact_lock(%s)',(1,))
        self.assertEqual(cloud.diagnostic(result.exception),dict(code='cloud-database-lock-timeout',operation='lock',automatic_retry=False))
        self.assertNotIn('PRIVATE',str(result.exception))
    def test_unknown_code_and_operation_are_not_exported(self):
        error=cloud.CloudDatabaseError('PRIVATE');error.operation='SELECT PRIVATE'
        self.assertEqual(cloud.diagnostic(error),dict(code='cloud-database-unavailable',operation='unknown',automatic_retry=False))
        self.assertIsNone(cloud.diagnostic(RuntimeError('PRIVATE')))
    def test_startup_timeout_scope_does_not_change_normal_transactions(self):
        raw=FakeRaw()
        with cloud.journal_initialization():
            db=cloud.Connection(raw,{},{});db.execute('BEGIN IMMEDIATE');db.execute('ROLLBACK')
        self.assertTrue(any("lock_timeout='60000'" in sql for sql,_ in raw.queries))
        raw=FakeRaw();db=cloud.Connection(raw,{},{});db.execute('BEGIN IMMEDIATE')
        self.assertTrue(any("lock_timeout='10000'" in sql for sql,_ in raw.queries))
        # The wider window wraps ONLY the advisory-lock statement; the effective
        # timeouts for the caller's body are restored to the normal bounded set.
        advisory=[i for i,(sql,_) in enumerate(raw.queries) if 'pg_advisory' in sql]
        self.assertEqual(len(advisory),1)
        self.assertIn("lock_timeout='60000'",raw.queries[advisory[0]-1][0])
        self.assertEqual(raw.queries[advisory[0]+1][0],
                         "SET LOCAL statement_timeout='15000'; SET LOCAL lock_timeout='10000'")
        # A read-only BEGIN takes no advisory lock and never widens.
        raw=FakeRaw();db=cloud.Connection(raw,{},{});db.execute('PRAGMA query_only=ON');db.execute('BEGIN')
        self.assertFalse(any('pg_advisory' in sql for sql,_ in raw.queries))
        self.assertFalse(any("lock_timeout='60000'" in sql for sql,_ in raw.queries))
    def test_contact_backfill_is_set_based_and_preserves_existing_bans(self):
        from mumu_peer_policy import initialize,backfill_contacts
        db=sqlite3.connect(':memory:')
        try:
            initialize(db)
            db.execute('CREATE TABLE chain_dialogs(account TEXT,peer TEXT,chat TEXT,stage TEXT)')
            db.executemany('INSERT INTO chain_dialogs VALUES(?,?,?,?)', [('a','first','c1','done'),('a','first','c2','done'),('a','null',None,'done'),('a','not-done','c3','declined')])
            db.execute("INSERT INTO mumu_peer_blocks(peer,reason,device,account,chat) VALUES('first','manual-block','telegram','','')")
            backfill_contacts(db)
            self.assertEqual(db.execute('SELECT peer,reason FROM mumu_peer_blocks').fetchall(),[('first','manual-block')])
            db.execute("INSERT INTO chain_dialogs VALUES('a','second','c4','done')")
            backfill_contacts(db)
            self.assertEqual(db.execute("SELECT reason FROM mumu_peer_blocks WHERE peer='second'").fetchone(),('contact-received',))
        finally:db.close()
