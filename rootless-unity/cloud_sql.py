"""Finite SQLite-to-Postgres bridge for the authored journal SQL, not user SQL."""
import re,sqlite3
from contextlib import closing

TYPES={'TEXT':'TEXT COLLATE "C"','INTEGER':'BIGINT','REAL':'DOUBLE PRECISION','BLOB':'BYTEA'}
IDENT=re.compile(r'^[a-z][a-z0-9_]{0,62}$')

def ident(value):
    if not isinstance(value,str) or not IDENT.fullmatch(value):raise ValueError('Invalid database identifier')
    return '"'+value+'"'

def placeholders(sql):
    # Never replace a literal ? or percent in a quoted SQL value/identifier.
    result=[];quote=None;i=0;bound=False
    while i<len(sql):
        c=sql[i]
        if quote:
            result.append('%%' if c=='%' else c)
            if c==quote:
                if i+1<len(sql) and sql[i+1]==quote:result.append(sql[i+1]);i+=1
                else:quote=None
        elif c in ("'",'"'):quote=c;result.append(c)
        elif c=='?':result.append('%s');bound=True
        elif c=='%':result.append('%%')
        else:result.append(c)
        i+=1
    if quote:raise ValueError('Unterminated authored SQL')
    text=''.join(result)
    return text if bound else text.replace('%%','%')

def schema_info(ddl):
    # SQLite itself parses the finite source DDL, without a disk DB, extensions
    # or executing any received DML/script. No arbitrary multi-statement SQL.
    m=re.match(r'\s*CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([a-z][a-z0-9_]*)\s*\(',ddl,re.I)
    if not m:raise ValueError('Unsupported authored DDL')
    name=m.group(1);ident(name)
    with closing(sqlite3.connect(':memory:')) as db:
        db.execute(ddl)
        columns=db.execute('PRAGMA table_info('+ident(name)+')').fetchall()
        if not columns or len(columns)>32:raise ValueError('Unsupported schema')
        for _,key,kind,_,default,_ in columns:
            ident(key)
            if kind.upper() not in TYPES or default not in (None,'CURRENT_TIMESTAMP'):raise ValueError('Unsupported column type/default')
        pk=[x[1] for x in sorted(columns,key=lambda x:x[5]) if x[5]]
        unique=[]
        for row in db.execute('PRAGMA index_list('+ident(name)+')').fetchall():
            if row[3]=='u':
                # SQLite-generated autoindex names can exceed PostgreSQL's
                # 63-character limit although the authored TABLE is valid.
                # Bind the internal name in SQLite only; never relax ident()
                # or emit this name into PostgreSQL DDL.
                unique.append([x[0] for x in db.execute(
                    'SELECT name FROM pragma_index_info(?) ORDER BY seqno',(row[1],))])
    return dict(name=name,columns=columns,pk=pk,unique=unique,
        identity=next((x[1] for x in columns if x[2].upper()=='INTEGER' and x[5] and len(pk)==1),None),sqlite_sql=ddl)

def create_sql(info):
    fields=[]
    for _,name,kind,notnull,default,position in info['columns']:
        text=ident(name)+' '+TYPES[kind.upper()]
        if name==info['identity']:text+=' GENERATED BY DEFAULT AS IDENTITY'
        if notnull or position:text+=' NOT NULL'
        if default=='CURRENT_TIMESTAMP':text+=" DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))"
        fields.append(text)
    if info['pk']:fields.append('PRIMARY KEY ('+','.join(map(ident,info['pk']))+')')
    for unique in info['unique']:fields.append('UNIQUE ('+','.join(map(ident,unique))+')')
    # Preserve the engine's explicit authorization checks, not only uniqueness.
    if info['name'].endswith('manual_actions'):
        fields.append('CHECK (confirmed=1)')
        fields.append("CHECK (status IN ('reserved-unknown','not-invoked','attempted-unknown','handler-returned-unconfirmed'))")
    return 'CREATE TABLE IF NOT EXISTS '+ident(info['name'])+'('+','.join(fields)+')'

def translate(sql,schemas):
    sql=sql.strip().rstrip(';')
    ignored=bool(re.match(r'INSERT\s+OR\s+IGNORE\s+',sql,re.I))
    replaced=bool(re.match(r'INSERT\s+OR\s+REPLACE\s+',sql,re.I))
    sql=re.sub(r'^INSERT\s+OR\s+(?:IGNORE|REPLACE)\s+','INSERT ',sql,flags=re.I)
    match=re.match(r'INSERT\s+INTO\s+([a-z][a-z0-9_]*)\b',sql,re.I)
    table=match.group(1) if match else None
    info=schemas.get(table) if table else None
    if ignored:sql+=' ON CONFLICT DO NOTHING'
    if replaced:
        if not info or not info['pk']:raise ValueError('Replace without known primary key')
        columns=[x[1] for x in info['columns'] if x[1] not in info['pk']]
        if not columns:raise ValueError('Replace without value columns')
        sql+=' ON CONFLICT ('+','.join(map(ident,info['pk']))+') DO UPDATE SET '+','.join(ident(x)+'=EXCLUDED.'+ident(x) for x in columns)
    returning=None
    if info and info['identity']:
        returning=info['identity'];sql+=' RETURNING '+ident(returning)
    # The only authored primary journal rowid ordering is read-only binding.
    if re.search(r'\browid\b',sql,re.I):
        if re.search(r'FROM\s+read_only_bindings\b',sql,re.I):sql=re.sub(r'ORDER\s+BY\s+rowid','ORDER BY created_at,account,peer',sql,flags=re.I)
        else:raise ValueError('Unsupported rowid query')
    return placeholders(sql),returning
